#!/data/data/com.termux/files/usr/bin/bash
# 构建控制台的外观引擎 res/console/theme.js（scripts/theme/engine.mjs + Material Color Utilities）。
# 依赖要联网装到临时目录；产物提交进仓库，平时构建二进制不需要 node。
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
WORK=$(mktemp -d "${TMPDIR:-/tmp}/acumen-theme.XXXXXX")
trap 'rm -rf "$WORK"' EXIT
NPM=(npm)
command -v npm >/dev/null && npm --version >/dev/null 2>&1 || NPM=(node "${PREFIX:-/usr}/lib/node_modules/npm/bin/npm-cli.js")
cp "$ROOT/scripts/theme/engine.mjs" "$WORK/engine.mjs"
cd "$WORK"
"${NPM[@]}" init -y >/dev/null
"${NPM[@]}" install --silent --no-audit --no-fund @material/material-color-utilities@0.4.0 esbuild@0.25.10 >/dev/null
node node_modules/esbuild/bin/esbuild engine.mjs --bundle --minify --format=iife --global-name=ZwTheme \
  --target=es2020 --legal-comments=none \
  --banner:js="/* @generated by scripts/make-theme.sh — 知微外观引擎；含 Material Color Utilities 0.4.0（Apache-2.0，© Google LLC） */" \
  --outfile="$ROOT/res/console/theme.js"
ls -l "$ROOT/res/console/theme.js"
