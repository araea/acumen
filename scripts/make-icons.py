#!/usr/bin/env python3
"""把控制台用到的图标从 Material Symbols 生成成一份内联精灵图。

为什么是 Material Symbols：界面的视觉体系是 Material 3 Expressive，它配套的图标就是
Material Symbols（Rounded 字形、字重 400、光学尺寸 24、GRAD 0）。笔画粗细、圆角半径与
字重和整套字阶、形状同出一源；旧版手绘的 2px 圆头描边图标与之只是「看起来差不多」。

选中态用实心（FILL 1）：导航与状态符号成对给出 `名字` 与 `名字-fill`，由 CSS 按
`aria-current` / 状态切换，不必在脚本里重画。

产物写进 `res/console/index.html` 里两行标记之间（`@generated by scripts/make-icons.py`），
界面用 `<svg><use href="#名字"/></svg>` 引用——内联而不是外部精灵文件，所以首帧就有图标，
也不多一条静态路由。

图标字形版权归 Google，Apache-2.0，见 THIRD_PARTY_NOTICES.md。

运行：python3 scripts/make-icons.py [--src <svg-400/rounded 目录>] [--check]
没给 --src 时用 `npm pack @material-symbols/svg-400` 取（需要联网与 npm）。
"""

import argparse
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "res/console/index.html"
PACKAGE = "@material-symbols/svg-400@0.48.0"

BEGIN = "<!-- @generated by scripts/make-icons.py — 不要手改这一段 -->"
END = "<!-- @end generated -->"

# 一个概念一个图标，全界面同一个：导航的「搭话」与插件「群聊搭话」同是 forum，
# 导航的「日志」与插件「日志输出」同是 receipt_long。
#
# 空格分隔；名字后面带 `+` 表示同时要实心版（选中 / 状态用）。
INVENTORY = """
dashboard+ extension+ forum+ receipt_long+ settings+

refresh search arrow_back chevron_right keyboard_arrow_down check close content_copy add delete
download vertical_align_bottom play_arrow logout visibility visibility_off key lock

error+ warning+ info+ check_circle+

groups person chat inbox hub smart_toy date_range tune terminal devices schedule

filter_alt admin_panel_settings web database perm_media add_reaction workspace_premium undo
campaign markdown repeat cloud leaderboard gif_box grid_view qr_code_scanner smart_display
music_note screenshot_monitor newspaper help restart_alt
"""

# 失败比悄悄缺一个图标好：缺了就在这里报出来。
def wanted():
    names = []
    for token in INVENTORY.split():
        solid = token.endswith("+")
        names.append((token.rstrip("+"), solid))
    return names


def source(arg):
    if arg:
        return Path(arg), None
    temp = Path(tempfile.mkdtemp(prefix="msym-"))
    subprocess.run(["npm", "pack", PACKAGE, "--silent"], cwd=temp, check=True, stdout=subprocess.DEVNULL)
    archive = next(temp.glob("*.tgz"))
    with tarfile.open(archive) as bundle:
        bundle.extractall(temp, filter="data")
    return temp / "package" / "rounded", temp


def path_data(file):
    text = file.read_text(encoding="utf-8")
    found = re.findall(r'<path d="([^"]+)"', text)
    if len(found) != 1:
        raise SystemExit(f"{file.name}: 期望恰好一条 path，实际 {len(found)}")
    return found[0]


def build(rounded):
    symbols = []
    missing = []
    for name, solid in wanted():
        outline = rounded / f"{name}.svg"
        if not outline.exists():
            missing.append(name)
            continue
        symbols.append((name, path_data(outline)))
        if solid:
            fill = rounded / f"{name}-fill.svg"
            if not fill.exists():
                missing.append(f"{name}-fill")
                continue
            symbols.append((f"{name}-fill", path_data(fill)))
    if missing:
        raise SystemExit("字形包里没有：" + "、".join(missing))
    body = "\n".join(
        f'<symbol id="{name}" viewBox="0 -960 960 960"><path d="{d}"/></symbol>' for name, d in symbols
    )
    return (
        f"{BEGIN}\n"
        f"<!-- Material Symbols Rounded · {PACKAGE} · Apache-2.0 · {len(symbols)} 个 -->\n"
        '<svg class="sprite" width="0" height="0" aria-hidden="true" focusable="false">\n'
        f"{body}\n</svg>\n{END}"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--src")
    parser.add_argument("--check", action="store_true", help="只检查 index.html 里的产物是不是最新，不写")
    args = parser.parse_args()

    rounded, temp = source(args.src)
    try:
        block = build(rounded)
    finally:
        if temp:
            shutil.rmtree(temp, ignore_errors=True)

    html = TARGET.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if pattern.search(html):
        updated = pattern.sub(lambda _: block, html)
    else:
        updated = html.replace("</body>", f"{block}\n</body>", 1)
    if args.check:
        if updated != html:
            sys.exit("index.html 里的图标不是最新：运行 python3 scripts/make-icons.py")
        print("图标已是最新")
        return
    TARGET.write_text(updated, encoding="utf-8")
    print(f"已写入 {TARGET.relative_to(ROOT)}：{block.count('<symbol')} 个字形")


if __name__ == "__main__":
    main()
