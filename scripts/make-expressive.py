#!/usr/bin/env python3
"""把 M3E 的形状与弹簧写进 res/console/tokens.css 的生成段。

两样东西 CSS 自己表达不了，只能先算好：

- 形状：M3E 形状库里的曲奇（cookie）与柔和爆发（soft burst）。知微的图标本身就是一枚
  曲奇，界面里的状态锚点、选中的分类与品牌光点都用这一族形状。这里按极坐标采样成 SVG
  路径，作为 `mask` 用的 data URI 令牌（`--zw-shape-*`）；
- 弹簧：M3E 的动效是阻尼弹簧（stiffness / damping ratio），不是贝塞尔曲线。这里按
  质量 1 的阻尼振子解析解采样，写成 `linear()` 缓动与对应的时长（`--md-sys-motion-*`）。
  app.js 的导航胶囊用同一组参数逐帧积分，两边手感一致。

用法：python3 scripts/make-expressive.py [--check]
"""

import math
import re
import sys
from pathlib import Path
from urllib.parse import quote

TOKENS = Path(__file__).resolve().parent.parent / "res/console/tokens.css"
BEGIN = "/* @generated by scripts/make-expressive.py — 不要手改这一段 */"
END = "/* @end expressive */"

# —— 形状 ——
# 半径 r(θ) = 1 - depth · (1 - |cos(nθ/2)|ˢ)：瓣宽而圆、谷窄；soft 越小，谷越圆。
SHAPES = {
    # 名字: (瓣数, 谷深, 谷的圆度, 起始角)
    "cookie9": (9, 0.11, 0.020, -90),
    "cookie12": (12, 0.075, 0.020, -90),
    "burst": (10, 0.17, 0.006, -90),
    "clover4": (4, 0.30, 0.050, -45),
}


def shape_path(lobes, depth, soft, start, samples=144):
    points = []
    for i in range(samples):
        t = 2 * math.pi * i / samples
        c = math.sqrt(math.cos(lobes * t / 2) ** 2 + soft) / math.sqrt(1 + soft)
        r = 1 - depth * (1 - c)
        a = t + math.radians(start)
        points.append((50 + 50 * r * math.cos(a), 50 + 50 * r * math.sin(a)))
    head = "M{:.2f} {:.2f}".format(*points[0])
    body = "".join("L{:.2f} {:.2f}".format(*p) for p in points[1:])
    return head + body + "Z"


def shape_uri(path):
    svg = f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'><path d='{path}'/></svg>"
    return 'url("data:image/svg+xml,' + quote(svg, safe="/:=' ") + '")'


# —— 弹簧（M3E motion scheme: expressive）——
# 名字: (stiffness, damping ratio)
SPRINGS = {
    "spatial-fast": (800, 0.6),
    "spatial-default": (380, 0.8),
    "spatial-slow": (200, 0.8),
    "effects-fast": (3800, 1.0),
    "effects-default": (1600, 1.0),
    "effects-slow": (800, 1.0),
}


def spring(stiffness, zeta, t):
    w0 = math.sqrt(stiffness)
    if zeta < 1:
        wd = w0 * math.sqrt(1 - zeta * zeta)
        return 1 - math.exp(-zeta * w0 * t) * (math.cos(wd * t) + zeta * w0 / wd * math.sin(wd * t))
    return 1 - math.exp(-w0 * t) * (1 + w0 * t)


def settle(stiffness, zeta, tolerance=0.002):
    """最后一次离终点超过 tolerance 的时刻，按 10ms 取整。"""
    last = 0.0
    t = 0.0
    while t < 3:
        if abs(1 - spring(stiffness, zeta, t)) > tolerance:
            last = t
        t += 0.001
    return math.ceil(last * 100) / 100


def easing(stiffness, zeta, duration, steps=40):
    values = [spring(stiffness, zeta, duration * i / steps) for i in range(steps + 1)]
    values[-1] = 1
    # 相邻三点共线的去掉：不影响曲线，只让字面量短一点。
    keep = [0]
    for i in range(1, steps):
        a, b, c = values[keep[-1]], values[i], values[i + 1]
        span = (i - keep[-1]) / (i + 1 - keep[-1])
        if abs(a + (c - a) * span - b) > 0.002:
            keep.append(i)
    keep.append(steps)
    parts = []
    for i in keep:
        v = f"{values[i]:.3f}".rstrip("0").rstrip(".") or "0"
        parts.append(v if i in (0, steps) else f"{v} {i * 100 / steps:g}%")
    return "linear(" + ", ".join(parts) + ")"


def block():
    lines = [BEGIN, ":root {"]
    lines.append("  /* M3E 形状（mask 用）：曲奇 9 / 12 瓣、柔和爆发、四叶草。 */")
    for name, spec in SHAPES.items():
        lines.append(f"  --zw-shape-{name}: {shape_uri(shape_path(*spec))};")
    lines.append("  /* M3E 弹簧（expressive）：stiffness / damping 采样成 linear()，时长是落定时刻。 */")
    for name, (k, z) in SPRINGS.items():
        d = settle(k, z)
        lines.append(f"  --md-sys-motion-{name}-duration: {round(d * 1000)}ms;")
        lines.append(f"  --md-sys-motion-{name}-easing: {easing(k, z, d)};")
    lines.append("}")
    lines.append(END)
    return "\n".join(lines)


def main():
    text = TOKENS.read_text()
    new = block()
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END), re.S)
    if pattern.search(text):
        out = pattern.sub(lambda _: new, text)
    else:
        index = text.index(":root {", text.index("界面这一份的取值"))
        out = text[:index] + new + "\n\n" + text[index:]
    if "--check" in sys.argv:
        if out != text:
            sys.exit("tokens.css 的 expressive 段与脚本不一致：跑一遍 scripts/make-expressive.py")
        return
    TOKENS.write_text(out)
    print("wrote", TOKENS)


if __name__ == "__main__":
    main()
